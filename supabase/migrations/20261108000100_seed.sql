from _seed_foods s
on conflict do nothing;

insert into public.food_servings (food_id, user_id, name, grams, is_default, position)
select f.id, null, srv.value ->> 0, (srv.value ->> 1)::numeric, srv.ordinality = 1, (srv.ordinality - 1)::smallint
from _seed_foods s
join public.foods f on f.source = 'seed' and f.source_id = s.sid and f.user_id is null
cross join lateral jsonb_array_elements(s.servings) with ordinality as srv(value, ordinality)
where not exists (select 1 from public.food_servings fs where fs.food_id = f.id);

