// Generates src/types/database.ts (Supabase format) from the migrations,
// without a live database. Prefer `npm run db:types` once the project is linked.
import fs from "node:fs";
import { bootDb } from "./lib/pglite-db.mjs";

const db = await bootDb();
const cols = (await db.query(`
  select c.table_name, c.column_name, c.data_type, c.udt_name, c.is_nullable, c.column_default, c.is_identity
  from information_schema.columns c
  join information_schema.tables t on t.table_name = c.table_name and t.table_schema = c.table_schema
  where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
  order by c.table_name, c.ordinal_position`)).rows;
const views = (await db.query(`
  select c.table_name, c.column_name, c.data_type, c.udt_name
  from information_schema.columns c
  join information_schema.tables t on t.table_name = c.table_name and t.table_schema = c.table_schema
  where c.table_schema = 'public' and t.table_type = 'VIEW'
  order by c.table_name, c.ordinal_position`)).rows;
const fks = (await db.query(`
  select con.conname as name, rel.relname as table_name, frel.relname as ref_table,
    array(select a.attname from unnest(con.conkey) k join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k) as cols,
    array(select a.attname from unnest(con.confkey) k join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k) as ref_cols
  from pg_constraint con
  join pg_class rel on rel.oid = con.conrelid
  join pg_namespace n on n.oid = rel.relnamespace
  join pg_class frel on frel.oid = con.confrelid
  join pg_namespace fn on fn.oid = frel.relnamespace
  where con.contype = 'f' and n.nspname = 'public' and fn.nspname = 'public'
  order by con.conname`)).rows;
const uniques = (await db.query(`
  select rel.relname as table_name, array(select a.attname from unnest(con.conkey) k join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k) as cols
  from pg_constraint con join pg_class rel on rel.oid = con.conrelid join pg_namespace n on n.oid = rel.relnamespace
  where con.contype in ('u','p') and n.nspname = 'public'`)).rows;
const fns = (await db.query(`
  select p.proname, pg_get_function_arguments(p.oid) as args, pg_get_function_result(p.oid) as result
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind = 'f'
    and pg_get_function_result(p.oid) <> 'trigger'
  order by p.proname`)).rows;

const scalar = (udt) => {
  switch (udt) {
    case "uuid": case "text": case "varchar": case "date": case "timestamptz": case "timestamp": case "time": case "bpchar": case "citext":
      return "string";
    case "int2": case "int4": case "int8": case "numeric": case "float4": case "float8":
      return "number";
    case "bool": return "boolean";
    case "json": case "jsonb": return "Json";
    default: return "unknown";
  }
};
const tsType = (c) => (c.data_type === "ARRAY" ? `${scalar(c.udt_name.slice(1))}[]` : scalar(c.udt_name));
const byTable = new Map();
for (const c of cols) {
  if (!byTable.has(c.table_name)) byTable.set(c.table_name, []);
  byTable.get(c.table_name).push(c);
}
const ind = (n) => " ".repeat(n);
let out = `// Generated by scripts/gen-types-local.mjs from supabase/migrations — do not edit by hand.
// Regenerate against the hosted project with \`npm run db:types\`.
export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  __InternalSupabase: {
    PostgrestVersion: "13.0.5";
  };
  public: {
    Tables: {
`;
for (const [table, tcols] of byTable) {
  const row = tcols.map((c) => `${ind(10)}${c.column_name}: ${tsType(c)}${c.is_nullable === "YES" ? " | null" : ""};`).join("\n");
  const ins = tcols.map((c) => {
    const opt = c.is_nullable === "YES" || c.column_default !== null || c.is_identity === "YES";
    return `${ind(10)}${c.column_name}${opt ? "?" : ""}: ${tsType(c)}${c.is_nullable === "YES" ? " | null" : ""};`;
  }).join("\n");
  const upd = tcols.map((c) => `${ind(10)}${c.column_name}?: ${tsType(c)}${c.is_nullable === "YES" ? " | null" : ""};`).join("\n");
  const rels = fks.filter((f) => f.table_name === table).map((f) => {
    const oneToOne = uniques.some((u) => u.table_name === table && u.cols.length === f.cols.length && u.cols.every((x) => f.cols.includes(x)));
    return `${ind(10)}{
${ind(12)}foreignKeyName: "${f.name}";
${ind(12)}columns: [${f.cols.map((x) => `"${x}"`).join(", ")}];
${ind(12)}isOneToOne: ${oneToOne};
${ind(12)}referencedRelation: "${f.ref_table}";
${ind(12)}referencedColumns: [${f.ref_cols.map((x) => `"${x}"`).join(", ")}];
${ind(10)}},`;
  }).join("\n");
  out += `${ind(6)}${table}: {
${ind(8)}Row: {
${row}
${ind(8)}};
${ind(8)}Insert: {
${ins}
${ind(8)}};
${ind(8)}Update: {
${upd}
${ind(8)}};
${ind(8)}Relationships: [${rels ? "\n" + rels + "\n" + ind(8) : ""}];
${ind(6)}};
`;
}
out += `${ind(4)}};
${ind(4)}Views: {`;
const byView = new Map();
for (const c of views) {
  if (!byView.has(c.table_name)) byView.set(c.table_name, []);
  byView.get(c.table_name).push(c);
}
if (byView.size === 0) out += `\n${ind(6)}[_ in never]: never;\n`;
else {
  out += "\n";
  for (const [v, vcols] of byView) {
    out += `${ind(6)}${v}: {\n${ind(8)}Row: {\n${vcols.map((c) => `${ind(10)}${c.column_name}: ${tsType(c)} | null;`).join("\n")}\n${ind(8)}};\n${ind(8)}Relationships: [];\n${ind(6)}};\n`;
  }
}
out += `${ind(4)}};
${ind(4)}Functions: {
`;
const pgArgType = (t) => {
  const m = t.trim().toLowerCase();
  if (m.endsWith("[]")) return pgArgType(m.slice(0, -2)) + "[]";
  if (/^(integer|bigint|smallint|numeric|real|double precision)/.test(m)) return "number";
  if (m === "boolean") return "boolean";
  if (m === "jsonb" || m === "json") return "Json";
  if (m === "void") return "undefined";
  return "string";
};
for (const f of fns) {
  const args = f.args ? f.args.split(",").map((a) => {
    const parts = a.trim().replace(/\s+default\s+.*$/i, "").split(/\s+/);
    const name = parts[0];
    const type = parts.slice(1).join(" ");
    const optional = /default/i.test(a);
    return `${name}${optional ? "?" : ""}: ${pgArgType(type)}`;
  }) : [];
  out += `${ind(6)}${f.proname}: {
${ind(8)}Args: ${args.length ? `{ ${args.join("; ")} }` : "Record<PropertyKey, never>"};
${ind(8)}Returns: ${pgArgType(f.result)};
${ind(6)}};
`;
}
out += `${ind(4)}};
${ind(4)}Enums: {
${ind(6)}[_ in never]: never;
${ind(4)}};
${ind(4)}CompositeTypes: {
${ind(6)}[_ in never]: never;
${ind(4)}};
${ind(2)}};
};

type PublicSchema = Database["public"];
export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];
export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];
export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"];
`;
fs.mkdirSync("src/types", { recursive: true });
fs.writeFileSync("src/types/database.ts", out);
console.log(`Wrote src/types/database.ts (${byTable.size} tables, ${fns.length} functions)`);
